export const SOLID_TILES = new Set(['#', 'W', 'R', 'B', 'Y', 'H', 'C', 'E', 'K']);

export function isTileWalkable(map: MapDefinition, x: number, y: number): boolean {
  if (x < 0 || y < 0 || x >= map.width || y >= map.height) return false;
  const ch = map.tiles[y]?.[x];
  if (!ch) return false;
  return !SOLID_TILES.has(ch);
}
